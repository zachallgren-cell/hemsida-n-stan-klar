import test from 'node:test';
import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {JSDOM} from 'jsdom';

test('handbook mounts inside admin, uses its client, keeps URL, saves and clears on logout',async()=>{
 const html=await readFile(new URL('../admin.html',import.meta.url),'utf8');
 const dom=new JSDOM(html,{url:'https://example.test/admin.html'});
 const {document}=dom.window;const root=document.getElementById('handbookPanel');
 assert.ok(root);assert.ok(document.querySelector('button[data-admin-view="handbook"]'));
 assert.equal(root.querySelectorAll('iframe').length,0,'editor must be mounted natively');
 assert.match(html,/handbookController\.setAuthorized\(isMfaVerified && !mustSetPassword\)/);
 assert.match(html,/handbookPanel\.classList\.toggle\('hidden', activeAdminView !== 'handbook'\)/);
 assert.match(html,/handbookController\.load\(activeAdminView\)/);
 globalThis.window=dom.window;globalThis.document=document;
 dom.window.confirm=()=>true;
 const {initHandbook}=await import('../handbook.mjs');
 const id='20000000-0000-4000-8000-000000000001';
 let record={id,revision:1,published_revision:1,updated_at:new Date().toISOString(),published_at:new Date().toISOString(),draft:{title:'Välkommen',category:'Kom igång',order:0,owner:'Berga',blocks:[{type:'text',text:'Godkänt innehåll'}]}};record.published=structuredClone(record.draft);
 let calls=0,authListener;
 const client={auth:{getSession:async()=>({data:{session:{}}}),onAuthStateChange(fn){authListener=fn;}},async rpc(name,args={}){calls++;if(name==='handbook_read')return {data:structuredClone(args.p_edit?[record]:[{id,document:record.published,revision:record.published_revision,updated_at:record.published_at}])};if(name==='handbook_save'){assert.equal(args.p_expected,record.revision);record={...record,draft:structuredClone(args.p_document),revision:record.revision+1};if(args.p_action==='publish'){record.published=structuredClone(record.draft);record.published_revision=record.revision;}return {data:structuredClone(record)};}throw new Error('Unexpected RPC');}};
 const controller=initHandbook({root,client,embedded:true});
 await controller.start();assert.equal(calls,0,'not loaded before admin authorization');
 controller.setAuthorized(true);await controller.start();
 assert.equal(root.querySelector('#app').hidden,false);
 root.querySelector('[data-open]').click();
 const title=root.querySelector('#edit-title');assert.ok(title);title.value='Nytt utkast';title.dispatchEvent(new dom.window.Event('input'));
 root.querySelector('#save').click();
 for(let i=0;i<20&&root.querySelector('#status').textContent!=='Sparat i databasen.';i++)await new Promise(resolve=>setTimeout(resolve,0));
 assert.equal(record.draft.title,'Nytt utkast');assert.equal(record.published.title,'Välkommen');
 assert.equal(dom.window.location.pathname,'/admin.html');assert.equal(dom.window.location.search,'');
 root.querySelector('#publish').click();
 for(let i=0;i<20&&root.querySelector('#status').textContent!=='Publicerat för personalen.';i++)await new Promise(resolve=>setTimeout(resolve,0));
 assert.equal(record.published.title,'Nytt utkast');
 record.draft.title='Privat andra utkast';let printed=false;dom.window.print=()=>{printed=true;};root.querySelector('#print').click();
 for(let i=0;i<20&&!printed;i++)await new Promise(resolve=>setTimeout(resolve,0));
 assert.equal(printed,true);assert.match(document.querySelector('.hb-print-output').textContent,/Nytt utkast/);assert.doesNotMatch(document.querySelector('.hb-print-output').textContent,/Privat andra utkast/);
 dom.window.dispatchEvent(new dom.window.Event('afterprint'));assert.equal(document.querySelector('.hb-print-output'),null);
 controller.setAuthorized(false);
 assert.equal(root.querySelector('#app').hidden,true);assert.equal(root.querySelector('#editor').textContent,'');assert.equal(root.querySelector('#articles').textContent,'');
 assert.equal(typeof authListener,'function');dom.window.close();delete globalThis.window;delete globalThis.document;
});
