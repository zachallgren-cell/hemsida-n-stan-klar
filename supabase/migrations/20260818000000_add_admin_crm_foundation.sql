create or replace function private.set_admin_crm_updated_at()
returns trigger
language plpgsql
set search_path = pg_catalog
as $$
begin
  new.updated_at := now();
  return new;
end;
$$;
revoke all on function private.set_admin_crm_updated_at() from public, anon, authenticated;

do $triggers$
declare
  table_name text;
  trigger_name text;
begin
  foreach table_name in array array['customers', 'customer_addresses', 'customer_notes', 'email_templates', 'automation_rules', 'scheduled_messages', 'follow_up_tasks']
  loop
    trigger_name := 'set_' || table_name || '_updated_at';
    execute format('drop trigger if exists %I on public.%I', trigger_name, table_name);
    execute format('create trigger %I before update on public.%I for each row execute function private.set_admin_crm_updated_at()', trigger_name, table_name);
  end loop;
end;
$triggers$;

do $rls$
declare
  table_name text;
begin
  foreach table_name in array array[
    'customers', 'customer_addresses', 'customer_tags', 'customer_tag_links',
    'customer_notes', 'email_templates', 'automation_rules', 'scheduled_messages',
    'communication_events', 'automation_runs', 'follow_up_tasks', 'admin_activity_log'
  ]
  loop
    execute format('alter table public.%I enable row level security', table_name);
    execute format('revoke all on table public.%I from public, anon', table_name);
  end loop;
end;
$rls$;

-- Editable admin-owned records.
do $editable_policies$
declare
  table_name text;
  policy_name text;
begin
  foreach table_name in array array[
    'customers', 'customer_addresses', 'customer_tags', 'customer_tag_links',
    'customer_notes', 'email_templates', 'automation_rules', 'scheduled_messages',
    'follow_up_tasks'
  ]
  loop
    policy_name := table_name || '_booking_admins_manage';
    execute format('grant select, insert, update, delete on table public.%I to authenticated', table_name);
    execute format('drop policy if exists %I on public.%I', policy_name, table_name);
    execute format('create policy %I on public.%I for all to authenticated using (private.is_booking_admin()) with check (private.is_booking_admin())', policy_name, table_name);
  end loop;
end;
$editable_policies$;

-- Append-only audit/timeline records: browser admins may read and append, but
-- never rewrite history. Service-role workers retain their normal bypass.
do $append_only_policies$
declare
  table_name text;
  read_policy text;
  insert_policy text;
begin
  foreach table_name in array array['communication_events', 'automation_runs', 'admin_activity_log']
  loop
    read_policy := table_name || '_booking_admins_read';
    insert_policy := table_name || '_booking_admins_append';
    execute format('grant select, insert on table public.%I to authenticated', table_name);
    execute format('revoke update, delete on table public.%I from authenticated', table_name);
    execute format('drop policy if exists %I on public.%I', read_policy, table_name);
    execute format('drop policy if exists %I on public.%I', insert_policy, table_name);
    execute format('create policy %I on public.%I for select to authenticated using (private.is_booking_admin())', read_policy, table_name);
    execute format('create policy %I on public.%I for insert to authenticated with check (private.is_booking_admin())', insert_policy, table_name);
  end loop;
end;
$append_only_policies$;

