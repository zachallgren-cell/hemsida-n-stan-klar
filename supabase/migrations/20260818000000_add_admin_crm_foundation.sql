-- Additive CRM and communication foundation for the admin redesign.
-- This migration deliberately does not backfill, rewrite or delete bookings,
-- and it does not change the existing Swish, payment or encrypted RUT flows.

set local search_path = pg_catalog, public, extensions;

create extension if not exists pgcrypto with schema extensions;

create table if not exists public.customers (
  id uuid primary key default extensions.gen_random_uuid(),
  display_name text not null check (char_length(btrim(display_name)) between 1 and 160),
  email text,
  phone text,
  customer_type text not null default 'private' check (customer_type in ('private', 'business')),
  lifecycle_status text not null default 'new' check (lifecycle_status in ('new', 'active', 'returning', 'inactive', 'paused', 'archived')),
  last_booking_at timestamp with time zone,
  next_booking_at timestamp with time zone,
  last_contacted_at timestamp with time zone,
  next_follow_up_at timestamp with time zone,
  review_status text not null default 'not_requested' check (review_status in ('not_requested', 'scheduled', 'request_sent', 'reminder_sent', 'received', 'do_not_contact')),
  review_requested_at timestamp with time zone,
  review_reminder_sent_at timestamp with time zone,
  review_received_at timestamp with time zone,
  automated_communication_paused boolean not null default false,
  communication_preferences jsonb not null default '{"service":true,"review":true,"marketing":false}'::jsonb,
  internal_notes text,
  assigned_admin_user_id uuid references auth.users(id) on delete set null,
  created_at timestamp with time zone not null default now(),
  updated_at timestamp with time zone not null default now(),
  constraint customers_review_dates_order check (
    review_reminder_sent_at is null or review_requested_at is null or review_reminder_sent_at >= review_requested_at
  )
);

create unique index if not exists customers_normalized_email_idx
  on public.customers (lower(btrim(email))) where email is not null and btrim(email) <> '';
create index if not exists customers_phone_idx on public.customers (phone) where phone is not null;
create index if not exists customers_follow_up_idx on public.customers (next_follow_up_at) where next_follow_up_at is not null;
create index if not exists customers_lifecycle_idx on public.customers (lifecycle_status, last_booking_at desc);

create table if not exists public.customer_addresses (
  id uuid primary key default extensions.gen_random_uuid(),
  customer_id uuid not null references public.customers(id) on delete cascade,
  label text,
  address_line text not null check (char_length(btrim(address_line)) between 1 and 500),
  postal_code text,
  city text,
  is_primary boolean not null default false,
  created_at timestamp with time zone not null default now(),
  updated_at timestamp with time zone not null default now()
);
create unique index if not exists customer_addresses_one_primary_idx
  on public.customer_addresses (customer_id) where is_primary;

create table if not exists public.customer_tags (
  id uuid primary key default extensions.gen_random_uuid(),
  name text not null check (char_length(btrim(name)) between 1 and 50),
  color text,
  created_at timestamp with time zone not null default now()
);
create unique index if not exists customer_tags_name_idx on public.customer_tags (lower(btrim(name)));

create table if not exists public.customer_tag_links (
  customer_id uuid not null references public.customers(id) on delete cascade,
  tag_id uuid not null references public.customer_tags(id) on delete cascade,
  created_at timestamp with time zone not null default now(),
  primary key (customer_id, tag_id)
);

create table if not exists public.customer_notes (
  id bigint generated by default as identity primary key,
  customer_id uuid not null references public.customers(id) on delete cascade,
  booking_id text,
  note text not null check (char_length(btrim(note)) between 1 and 5000),
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamp with time zone not null default now(),
  updated_at timestamp with time zone not null default now()
);
create index if not exists customer_notes_customer_idx on public.customer_notes (customer_id, created_at desc);

create table if not exists public.email_templates (
  id uuid primary key default extensions.gen_random_uuid(),
  template_key text not null check (template_key ~ '^[a-z0-9_]{3,80}$'),
  name text not null,
  subject text not null check (char_length(subject) between 1 and 300),
  html_body text not null,
  text_body text not null,
  allowed_variables text[] not null default '{}',
  version integer not null default 1 check (version > 0),
  active boolean not null default false,
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamp with time zone not null default now(),
  updated_at timestamp with time zone not null default now(),
  unique (template_key, version)
);

create table if not exists public.automation_rules (
  id uuid primary key default extensions.gen_random_uuid(),
  rule_key text not null unique check (rule_key ~ '^[a-z0-9_]{3,80}$'),
  name text not null,
  trigger_type text not null,
  delay_seconds integer not null default 0 check (delay_seconds between 0 and 31557600),
  conditions jsonb not null default '{}'::jsonb,
  action_type text not null default 'send_email' check (action_type in ('send_email', 'create_task')),
  email_template_id uuid references public.email_templates(id) on delete restrict,
  stop_conditions jsonb not null default '{}'::jsonb,
  active boolean not null default false,
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamp with time zone not null default now(),
  updated_at timestamp with time zone not null default now(),
  constraint automation_email_template_required check (action_type <> 'send_email' or email_template_id is not null)
);

create table if not exists public.scheduled_messages (
  id uuid primary key default extensions.gen_random_uuid(),
  customer_id uuid references public.customers(id) on delete cascade,
  booking_id text,
  automation_id uuid references public.automation_rules(id) on delete set null,
  email_template_id uuid references public.email_templates(id) on delete restrict,
  template_version integer,
  message_type text not null,
  recipient_email text not null,
  scheduled_for timestamp with time zone not null,
  status text not null default 'scheduled' check (status in ('scheduled', 'sending', 'sent', 'failed', 'skipped', 'cancelled', 'paused')),
  idempotency_key text not null check (char_length(idempotency_key) between 16 and 200),
  attempt_count integer not null default 0 check (attempt_count between 0 and 20),
  provider_message_id text,
  last_error_code text,
  stopped_reason text,
  trigger_snapshot jsonb not null default '{}'::jsonb,
  created_at timestamp with time zone not null default now(),
  updated_at timestamp with time zone not null default now(),
  sent_at timestamp with time zone,
  unique (idempotency_key)
);
create index if not exists scheduled_messages_due_idx
  on public.scheduled_messages (scheduled_for) where status = 'scheduled';
create index if not exists scheduled_messages_customer_idx
  on public.scheduled_messages (customer_id, created_at desc);
create unique index if not exists scheduled_messages_provider_id_idx
  on public.scheduled_messages (provider_message_id) where provider_message_id is not null;

