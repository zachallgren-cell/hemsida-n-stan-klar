create table if not exists public.clarity_api_daily_usage (
  usage_date date primary key,
  reserved_calls smallint not null default 0 check (reserved_calls between 0 and 9),
  updated_at timestamp with time zone not null default now()
);

alter table public.clarity_api_daily_usage enable row level security;
alter table public.clarity_api_daily_usage force row level security;
revoke all on table public.clarity_api_daily_usage from public, anon, authenticated;

create or replace function public.reserve_clarity_api_calls(p_call_count integer)
returns boolean
language plpgsql
security definer
set search_path = pg_catalog, public
as $$
declare
  stockholm_date date := (now() at time zone 'Europe/Stockholm')::date;
  current_count integer;
begin
  if p_call_count < 1 or p_call_count > 3 then
    return false;
  end if;

  perform pg_advisory_xact_lock(hashtext('clarity-api-daily-budget'));
  select reserved_calls into current_count
  from public.clarity_api_daily_usage
  where usage_date = stockholm_date;

  current_count := coalesce(current_count, 0);
  if current_count + p_call_count > 9 then
    return false;
  end if;

  insert into public.clarity_api_daily_usage (usage_date, reserved_calls, updated_at)
  values (stockholm_date, current_count + p_call_count, now())
  on conflict (usage_date) do update
    set reserved_calls = excluded.reserved_calls,
        updated_at = excluded.updated_at;
  return true;
end;
$$;

revoke all on function public.reserve_clarity_api_calls(integer) from public, anon, authenticated;
grant execute on function public.reserve_clarity_api_calls(integer) to service_role;

