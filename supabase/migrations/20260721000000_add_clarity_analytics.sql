create table if not exists public.clarity_analytics_snapshots (
  id bigint generated by default as identity primary key,
  snapshot_date date not null,
  period_start timestamp with time zone not null,
  period_end timestamp with time zone not null,
  fetched_at timestamp with time zone not null default now(),
  project_id text not null,
  dimension_key text not null,
  dimensions text[] not null,
  metrics jsonb not null,
  row_count integer not null default 0 check (row_count >= 0 and row_count <= 1000),
  schema_version integer not null default 1,
  constraint clarity_snapshot_period_valid check (period_end > period_start),
  constraint clarity_snapshot_dimensions_valid check (cardinality(dimensions) between 1 and 3),
  constraint clarity_snapshot_unique unique (snapshot_date, project_id, dimension_key)
);

comment on table public.clarity_analytics_snapshots is
  'Aggregerade Clarity Data Export-snapshots. Inga tokens, inspelningar eller direkt identifierande kunduppgifter.';

