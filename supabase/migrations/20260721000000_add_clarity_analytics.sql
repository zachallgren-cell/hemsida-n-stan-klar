create or replace function private.purge_old_clarity_analytics()
returns void
language plpgsql
security definer
set search_path = pg_catalog, public
as $$
begin
  delete from public.clarity_analytics_snapshots
  where snapshot_date < (now() at time zone 'Europe/Stockholm')::date - 270;

  delete from public.clarity_api_daily_usage
  where usage_date < (now() at time zone 'Europe/Stockholm')::date - 14;
end;
$$;

revoke all on function private.purge_old_clarity_analytics() from public, anon, authenticated, service_role;

